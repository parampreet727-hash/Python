name = "Parampreet Dhatt"
age = 25

# Comma 
print("My name is",name,"and my age is",age)
#Output - My name is Parampreet Dhatt and my age is 25

# f-string
print(f"My name is {name} and my age is {age}")
#Output - My name is Parampreet Dhatt and my age is 25

# Format method
print("my name is {} and my age is {}".format(name,age))
#Output - My name is Parampreet Dhatt and my age is 25
